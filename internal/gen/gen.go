// Package gen turns a spec.Service into Bruno OpenCollection documents.
//
// The output mirrors what `bru import openapi` produces (checked against
// @usebruno/cli 4.3.0), with three differences: base URLs come from per
// service collection variables, request bodies get generated examples, and
// requests are grouped under one folder per service.
package gen

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/jehadbaeth/brunosync/internal/ocyaml"
	"github.com/jehadbaeth/brunosync/internal/spec"
)

// Request is one generated request file.
type Request struct {
	Key      string // "<service>/<operation id>", the identity used by sync
	Service  string
	ID       string
	Dir      string // directory relative to the collection root, forward slashes
	FileName string
	Doc      *ocyaml.Map
}

// RelPath is the request file path relative to the collection root.
func (r Request) RelPath() string { return r.Dir + "/" + r.FileName }

// Folder is a folder.yml that is created when missing and never modified.
type Folder struct {
	Dir string
	Doc *ocyaml.Map
}

// Variable is a collection variable owned by brunosync.
type Variable struct {
	Name        string
	Value       string
	Description string
}

// Output is everything generated for one service.
type Output struct {
	Service   *spec.Service
	Dir       string
	Requests  []Request
	Folders   []Folder
	Variables []Variable
}

var (
	pathParamRe = regexp.MustCompile(`\{([^{}]+)\}`)
	unsafeFile  = regexp.MustCompile(`[^A-Za-z0-9._-]+`)
	varUnsafe   = regexp.MustCompile(`[^A-Za-z0-9_]+`)
)

// VarPrefix is the collection variable prefix for a service, e.g.
// "flight-dynamics" -> "flight_dynamics_".
func VarPrefix(service string) string {
	return strings.Trim(varUnsafe.ReplaceAllString(service, "_"), "_") + "_"
}

// FileSafe turns an identity into a file name stem.
func FileSafe(s string) string {
	s = strings.Trim(unsafeFile.ReplaceAllString(s, "-"), "-.")
	if s == "" {
		return "request"
	}
	return s
}

// Service generates all documents for one service. Dir is the service folder
// name inside the collection.
func Service(svc *spec.Service, dir string) Output {
	out := Output{Service: svc, Dir: dir}
	prefix := VarPrefix(svc.Name)
	q := func(s string) string { return qualify(s, prefix) }

	for _, v := range svc.Server.Vars {
		out.Variables = append(out.Variables, Variable{Name: prefix + v.Name, Value: v.Value, Description: v.Description})
	}
	baseVar := prefix + "baseUrl"
	out.Variables = append(out.Variables, Variable{
		Name:        baseVar,
		Value:       q(svc.Server.BaseURL),
		Description: "built from the other " + strings.TrimSuffix(prefix, "_") + " variables, override those instead",
	})

	tagDocs := map[string]string{}
	for _, t := range svc.Tags {
		tagDocs[t.Name] = t.Description
	}

	out.Folders = append(out.Folders, Folder{Dir: dir, Doc: folderDoc(svc.Folder, serviceDocs(svc))})
	seenTagDirs := map[string]string{}
	usedNames := map[string]bool{}

	for _, op := range svc.Operations {
		reqDir := dir
		if len(op.Tags) > 0 && strings.TrimSpace(op.Tags[0]) != "" {
			tag := op.Tags[0]
			// Tags that differ only in case ("Webhooks", "webhooks") share a
			// folder: on macOS and Windows they would be the same directory.
			key := strings.ToLower(FileSafe(tag))
			if existing, ok := seenTagDirs[key]; ok {
				reqDir = existing
			} else {
				reqDir = dir + "/" + FileSafe(tag)
				seenTagDirs[key] = reqDir
				out.Folders = append(out.Folders, Folder{Dir: reqDir, Doc: folderDoc(tag, tagDocs[tag])})
			}
		}
		stem := FileSafe(op.ID)
		if !op.HasOperationID {
			stem = FileSafe(strings.ToLower(op.Method + "-" + op.Path))
		}
		name := stem + ".yml"
		for i := 2; usedNames[strings.ToLower(reqDir+"/"+name)]; i++ {
			name = fmt.Sprintf("%s-%d.yml", stem, i)
		}
		usedNames[strings.ToLower(reqDir+"/"+name)] = true

		out.Requests = append(out.Requests, Request{
			Key:      svc.Name + "/" + op.ID,
			Service:  svc.Name,
			ID:       op.ID,
			Dir:      reqDir,
			FileName: name,
			Doc:      requestDoc(op, "{{"+baseVar+"}}"),
		})
	}
	return out
}

func qualify(s, prefix string) string {
	return regexp.MustCompile(`\{\{([A-Za-z0-9_]+)\}\}`).ReplaceAllString(s, "{{"+prefix+"$1}}")
}

func serviceDocs(svc *spec.Service) string {
	var b strings.Builder
	if svc.Title != "" {
		fmt.Fprintf(&b, "# %s\n\n", svc.Title)
	}
	if svc.Description != "" {
		b.WriteString(svc.Description)
		b.WriteString("\n\n")
	}
	if svc.Version != "" {
		fmt.Fprintf(&b, "* Version: %s\n", svc.Version)
	}
	fmt.Fprintf(&b, "* Source: `%s`\n", svc.Source)
	fmt.Fprintf(&b, "* Base URL variables: `%s*` (collection variables, override them in an environment)\n\n", VarPrefix(svc.Name))
	b.WriteString("Generated by brunosync. This folder file is only created once, edits are kept.")
	return b.String()
}

func folderDoc(name, docs string) *ocyaml.Map {
	m := ocyaml.M(
		"info", ocyaml.M("name", name, "type", "folder"),
		"request", ocyaml.M("auth", "inherit"),
	)
	if strings.TrimSpace(docs) != "" {
		m.Set("docs", ocyaml.M("content", docs, "type", "text/markdown"))
	}
	return m
}

// QueryString renders the enabled query params the way Bruno keeps them in
// the URL ("?a=1&b=2"). The Bruno CLI only sends query params that are in the
// URL, the params list alone is not enough (checked with bru 4.3.0).
func QueryString(params []any) string {
	var parts []string
	for _, p := range params {
		m, ok := p.(*ocyaml.Map)
		if !ok || m.String("type") != "query" || m.Value("disabled") == true {
			continue
		}
		parts = append(parts, m.String("name")+"="+m.String("value"))
	}
	if len(parts) == 0 {
		return ""
	}
	return "?" + strings.Join(parts, "&")
}

// RequestURL converts an OpenAPI path into a Bruno URL with :params.
func RequestURL(base, path string) string {
	return base + pathParamRe.ReplaceAllString(path, ":$1")
}

func requestDoc(op spec.Operation, base string) *ocyaml.Map {
	name := op.Summary
	if name == "" {
		name = op.ID
	}
	info := ocyaml.M("name", name, "type", "http")
	if len(op.Tags) > 0 {
		info.Set("tags", stringList(op.Tags))
	}

	headers, params := paramLists(op.Params)
	url := RequestURL(base, op.Path) + QueryString(params)
	httpBlock := ocyaml.M("method", op.Method, "url", url)
	if len(headers) > 0 {
		httpBlock.Set("headers", headers)
	}
	if len(params) > 0 {
		httpBlock.Set("params", params)
	}
	if body := bodyDoc(op.Body); body != nil {
		httpBlock.Set("body", body)
	}
	httpBlock.Set("auth", "inherit")

	doc := ocyaml.M(
		"info", info,
		"http", httpBlock,
		"settings", ocyaml.M(
			"encodeUrl", true,
			"timeout", int64(0),
			"followRedirects", true,
			"maxRedirects", int64(5),
			"forwardAuthorizationHeader", true,
		),
	)
	if ex := examples(op, url, headers, params); len(ex) > 0 {
		doc.Set("examples", ex)
	}
	if d := requestDocs(op); d != "" {
		doc.Set("docs", d)
	}
	return doc
}

func requestDocs(op spec.Operation) string {
	var parts []string
	if op.Deprecated {
		parts = append(parts, "**Deprecated.**")
	}
	if op.Summary != "" && op.Description != "" {
		parts = append(parts, op.Description)
	} else if op.Description != "" {
		parts = append(parts, op.Description)
	}
	return strings.Join(parts, "\n\n")
}

func stringList(in []string) []any {
	out := make([]any, len(in))
	for i, s := range in {
		out[i] = s
	}
	return out
}

func paramLists(ps []spec.Param) (headers, params []any) {
	for _, p := range ps {
		entry := ocyaml.M("name", p.Name, "value", p.Value)
		if p.In != "header" {
			entry.Set("type", p.In)
		}
		if p.Description != "" {
			entry.Set("description", p.Description)
		}
		if !p.Required {
			entry.Set("disabled", true)
		}
		if p.In == "header" {
			headers = append(headers, entry)
		} else {
			params = append(params, entry)
		}
	}
	// Path params first, in URL order, then query params, like Bruno does.
	sort.SliceStable(params, func(i, j int) bool {
		return params[i].(*ocyaml.Map).String("type") == "path" && params[j].(*ocyaml.Map).String("type") != "path"
	})
	return headers, params
}

func bodyDoc(b *spec.Body) *ocyaml.Map {
	if b == nil {
		return nil
	}
	switch b.Mode {
	case spec.BodyFormURL:
		var data []any
		for _, f := range b.Fields {
			e := ocyaml.M("name", f.Name, "value", f.Value)
			if !f.Required {
				e.Set("disabled", true)
			}
			data = append(data, e)
		}
		m := ocyaml.M("type", "form-urlencoded")
		if len(data) > 0 {
			m.Set("data", data)
		}
		return m
	case spec.BodyMultipartForm:
		var data []any
		for _, f := range b.Fields {
			e := ocyaml.M("name", f.Name)
			if f.IsFile {
				e.Set("type", "file")
				e.Set("value", []any{})
			} else {
				e.Set("type", "text")
				e.Set("value", f.Value)
			}
			if !f.Required {
				e.Set("disabled", true)
			}
			data = append(data, e)
		}
		m := ocyaml.M("type", "multipart-form")
		if len(data) > 0 {
			m.Set("data", data)
		}
		return m
	default:
		return ocyaml.M("type", b.Mode, "data", b.Raw)
	}
}

func examples(op spec.Operation, url string, headers, params []any) []any {
	var out []any
	for _, r := range op.Responses {
		req := ocyaml.M("url", url, "method", op.Method)
		if len(headers) > 0 {
			req.Set("headers", ocyaml.Clone(headers))
		}
		if len(params) > 0 {
			req.Set("params", ocyaml.Clone(params))
		}
		if body := bodyDoc(op.Body); body != nil {
			req.Set("body", body)
		}
		resp := ocyaml.M("status", int64(r.Status), "statusText", spec.StatusText(r.Status))
		if r.ContentType != "" {
			resp.Set("headers", []any{ocyaml.M("name", "Content-Type", "value", r.ContentType)})
		}
		resp.Set("body", ocyaml.M("type", r.BodyType, "data", r.Body))
		ex := ocyaml.M("name", fmt.Sprintf("%d Response", r.Status))
		if r.Description != "" {
			ex.Set("description", r.Description)
		}
		ex.Set("request", req)
		ex.Set("response", resp)
		out = append(out, ex)
	}
	return out
}
